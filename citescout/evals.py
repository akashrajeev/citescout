"""Measure the checks instead of asserting they work.

``citescout eval`` runs a fixed question set (SerpApi results, plans and pages are cached, so a
re-run costs 0 credits), saves each brief as JSON, and scores it:

- citation validity: every cited id exists in the evidence (must be 100%);
- deep-read rate: share of shipped claims whose facts were found in a cited page or API record;
- planted-error test: for every claim that deep-read verified and that states a hard fact
  (version, number, date), code changes that fact (2.34.2 -> 2.34.3, 278 -> 279, 2026 -> 2027)
  and re-checks the claim against the same cached pages. A caught plant is one that is no
  longer verified. This estimates how often a wrong number would slip through.
"""

from __future__ import annotations

import json
import re
from dataclasses import asdict, dataclass
from pathlib import Path

from citescout.deepread import PageStore, check_claim, hard_facts
from citescout.models import Brief, Claim, Engine

DEFAULT_QUESTIONS = [
    "Is the Python requests library still maintained, or should I switch to httpx?",
    'Is moment.js still maintained, or should I move to date-fns or Day.js?',
    'Is HNSW still the best approximate nearest neighbor index for vector search, or have newer indexes like DiskANN or ScaNN overtaken it?',
]


def mutate(fact: str) -> str:
    """A plausible wrong value: bump the last number component by one."""
    parts = fact.split(".")
    last = parts[-1]
    parts[-1] = str(int(last) + 1).zfill(len(last)) if last.isdigit() else last
    return ".".join(parts)


def plant(claim: Claim) -> Claim | None:
    facts = hard_facts(claim.text)
    if not facts:
        return None
    f = facts[0]
    wrong = mutate(f)
    pattern = re.compile(rf"(?<![0-9.]){re.escape(f)}(?![0-9])")
    text = pattern.sub(wrong, claim.text, count=1)
    if text == claim.text:  # the fact was written with separators ("52,000"); rebuild it
        raw = next((m.group(0) for m in re.finditer(r"\d{1,3}(?:[ ,\u00a0\u202f\u2009]\d{3})+(?!\d)|\d+", claim.text)
                    if re.sub(r"\D", "", m.group(0)) == f), None)
        if raw is None:
            return None
        text = claim.text.replace(raw, wrong, 1)
    return claim.model_copy(update={"text": text})


@dataclass
class Score:
    question: str
    claims: int
    citations_valid: float
    page_verified: int
    snippet_only: int
    unconfirmed: int
    dropped: int
    unlinked: int
    contradictions: int
    planted: int
    caught: int
    followups: int
    comparison_rows: int


def score(brief: Brief, store: PageStore) -> Score:
    by_id = {e.id: e for e in brief.evidence}
    cites = [i for c in brief.claims for i in c.citations]
    valid = sum(1 for i in cites if i in by_id) / len(cites) if cites else 1.0
    urls = {by_id[i].url for i in cites if i in by_id and by_id[i].engine not in (None, Engine.GOOGLE_TRENDS)}
    pages = {u: store.get(u, None) for u in urls}  # cache only: never re-fetch during scoring
    planted = caught = 0
    for c in brief.claims:
        if c.verification != "page":
            continue
        bad = plant(c)
        if bad is None:
            continue
        planted += 1
        if check_claim(bad, by_id, pages)[0] != "page":
            caught += 1
    status = [c.verification for c in brief.claims]
    return Score(question=brief.question, claims=len(brief.claims), citations_valid=valid,
                 page_verified=status.count("page"), snippet_only=status.count("snippet"),
                 unconfirmed=status.count("unconfirmed"), dropped=brief.dropped_claims,
                 unlinked=brief.unlinked_citations, contradictions=len(brief.contradictions),
                 planted=planted, caught=caught, followups=len(brief.followups),
                 comparison_rows=len(brief.comparison.rows) if brief.comparison else 0)


def report(scores: list[Score]) -> str:
    tot = lambda k: sum(getattr(s, k) for s in scores)  # noqa: E731
    claims, planted = tot("claims"), tot("planted")
    lines = ["# citescout eval", "",
             "Generated by `citescout eval` from cached SerpApi results and pages (0 credits to re-run).", "",
             "| Question | Claims | Valid citations | Verified on page | Snippet only | Not found | "
             "Dropped | Unlinked | Disagreements | Round-2 searches | Planted errors caught |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in scores:
        lines.append(f"| {s.question} | {s.claims} | {s.citations_valid:.0%} | {s.page_verified} | {s.snippet_only} | "
                     f"{s.unconfirmed} | {s.dropped} | {s.unlinked} | {s.contradictions} | {s.followups} | "
                     f"{s.caught}/{s.planted} |")
    lines += ["", f"**Totals:** {claims} shipped claims, "
                  f"{tot('page_verified')} ({tot('page_verified') / max(claims, 1):.0%}) verified against a full page "
                  f"or live API record, {tot('unconfirmed')} not found (confidence lowered), "
                  f"{tot('dropped')} unsupported claims dropped before shipping, {tot('unlinked')} off-subject "
                  f"citations unlinked. Planted wrong facts caught: {tot('caught')}/{planted}"
                  + (f" ({tot('caught') / planted:.0%})." if planted else "."), "",
              "A planted error changes one hard fact in a verified claim (2.34.2 -> 2.34.3, 2026 -> 2027) and "
              "re-checks it against the same cached pages. Word coverage alone does not catch plants in claims "
              "that state no number; those are covered by the citation and subject gates instead."]
    return "\n".join(lines) + "\n"


def run(questions: list[str], agent_factory, out_dir: Path, store: PageStore) -> list[Score]:  # noqa: ANN001
    out_dir.mkdir(parents=True, exist_ok=True)
    scores = []
    for q in questions:
        brief = agent_factory().run(q)
        slug = re.sub(r"[^a-z0-9]+", "-", q.lower()).strip("-")[:60]
        (out_dir / f"{slug}.json").write_text(json.dumps(brief.model_dump(mode="json"), indent=1))
        scores.append(score(brief, store))
    (out_dir / "scores.json").write_text(json.dumps([asdict(s) for s in scores], indent=1))
    return scores


def rescore(out_dir: Path, store: PageStore) -> list[Score]:
    """Re-check the saved briefs with the current deep-read rules (no LLM, no SerpApi)."""
    from citescout.deepread import deep_verify

    scores = []
    for path in sorted(out_dir.glob("*.json")):
        if path.name == "scores.json":
            continue
        brief = Brief.model_validate_json(path.read_text())
        rep = deep_verify(brief.claims, brief.evidence, store)
        brief.pages_read, brief.claims_page_verified, brief.claims_unconfirmed = rep.pages_read, rep.page_verified, rep.unconfirmed
        path.write_text(json.dumps(brief.model_dump(mode="json"), indent=1))
        scores.append(score(brief, store))
    (out_dir / "scores.json").write_text(json.dumps([asdict(s) for s in scores], indent=1))
    return scores
